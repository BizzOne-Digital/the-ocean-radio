function norm(s) {
  return s
    .trim()
    .replace(/_/g, " ")
    .replace(/\s+/g, " ")
    .toUpperCase();
}

function parse(block) {
  return block
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const [artist, ...rest] = line.split("|");
      let title = rest.join("|").trim();
      if (title === "GIRLS JUST WANT TO HAVE FU") title = "GIRLS JUST WANT TO HAVE FUN";
      return { artist: artist.trim(), title };
    });
}

const seen = new Set();
const tracks = [];
for (const t of [...parse(block1), ...parse(block2)]) {
  const key = `${norm(t.artist)}|${norm(t.title)}`;
  if (seen.has(key)) continue;
  seen.add(key);
  tracks.push({ id: `rf-${tracks.length + 1}`, artist: t.artist, title: t.title });
}

import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const dir = dirname(fileURLToPath(import.meta.url));
writeFileSync(
  join(dir, "../src/data/relaxing-favorites.json"),
  JSON.stringify({ slot: "relaxing-favorites", timezone: "Asia/Manila", hours: "00:00-21:00", tracks }, null, 2),
);
